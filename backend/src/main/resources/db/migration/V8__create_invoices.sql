CREATE SEQUENCE invoice_number_seq START WITH 1 INCREMENT BY 1;

CREATE TABLE invoices (
                          id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
                          invoice_number VARCHAR(30)   NOT NULL,
                          order_id       BIGINT        NOT NULL,
                          issue_date     DATE          NOT NULL,
                          due_date       DATE          NOT NULL,
                          subtotal       NUMERIC(14,3) NOT NULL,
                          tax_amount     NUMERIC(14,3) NOT NULL DEFAULT 0,
                          discount       NUMERIC(14,3) NOT NULL DEFAULT 0,
                          total_amount   NUMERIC(14,3) NOT NULL,
                          status         VARCHAR(20)   NOT NULL DEFAULT 'DRAFT',
                          payment_status VARCHAR(20)   NOT NULL DEFAULT 'UNPAID',
                          created_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
                          updated_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
                          CONSTRAINT pk_invoices PRIMARY KEY (id),
                          CONSTRAINT uq_invoices_invoice_number UNIQUE (invoice_number),
                          CONSTRAINT uq_invoices_order_id UNIQUE (order_id),
                          CONSTRAINT fk_invoices_orders FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE RESTRICT,
                          CONSTRAINT ck_invoices_subtotal CHECK (subtotal >= 0),
                          CONSTRAINT ck_invoices_tax_amount CHECK (tax_amount >= 0),
                          CONSTRAINT ck_invoices_discount CHECK (discount >= 0),
                          CONSTRAINT ck_invoices_due_date CHECK (due_date >= issue_date),
                          CONSTRAINT ck_invoices_total CHECK (total_amount = subtotal - discount + tax_amount),
                          CONSTRAINT ck_invoices_status CHECK (status IN
                                                               ('DRAFT', 'ISSUED', 'PAID', 'OVERDUE', 'CANCELLED')),
                          CONSTRAINT ck_invoices_payment_status CHECK (payment_status IN
                                                                       ('UNPAID', 'PARTIALLY_PAID', 'PAID'))
);

CREATE INDEX idx_invoices_status ON invoices (status);
CREATE INDEX idx_invoices_payment_status ON invoices (payment_status);
CREATE INDEX idx_invoices_due_date ON invoices (due_date);