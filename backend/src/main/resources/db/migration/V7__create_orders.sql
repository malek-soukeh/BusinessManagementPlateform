CREATE SEQUENCE order_number_seq START WITH 1 INCREMENT BY 1;

CREATE TABLE orders (
                        id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
                        order_number VARCHAR(30)   NOT NULL,
                        customer_id  BIGINT        NOT NULL,
                        order_date   TIMESTAMPTZ   NOT NULL DEFAULT now(),
                        status       VARCHAR(20)   NOT NULL DEFAULT 'PENDING',
                        total_amount NUMERIC(14,3) NOT NULL DEFAULT 0,
                        created_by   BIGINT        NOT NULL,
                        created_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
                        updated_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
                        CONSTRAINT pk_orders PRIMARY KEY (id),
                        CONSTRAINT uq_orders_order_number UNIQUE (order_number),
                        CONSTRAINT fk_orders_customers FOREIGN KEY (customer_id) REFERENCES customers (id) ON DELETE RESTRICT,
                        CONSTRAINT fk_orders_users FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE RESTRICT,
                        CONSTRAINT ck_orders_total CHECK (total_amount >= 0),
                        CONSTRAINT ck_orders_status CHECK (status IN
                                                           ('PENDING', 'CONFIRMED', 'SHIPPED', 'DELIVERED', 'CANCELLED'))
);

CREATE INDEX idx_orders_customer_id ON orders (customer_id);
CREATE INDEX idx_orders_status ON orders (status);
CREATE INDEX idx_orders_order_date ON orders (order_date);
CREATE INDEX idx_orders_created_by ON orders (created_by);

CREATE TABLE order_items (
                             id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
                             order_id   BIGINT        NOT NULL,
                             product_id BIGINT        NOT NULL,
                             quantity   INTEGER       NOT NULL,
                             unit_price NUMERIC(14,3) NOT NULL,
                             subtotal   NUMERIC(14,3) NOT NULL,
                             CONSTRAINT pk_order_items PRIMARY KEY (id),
                             CONSTRAINT fk_order_items_orders FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE,
                             CONSTRAINT fk_order_items_products FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE RESTRICT,
                             CONSTRAINT uq_order_items_order_product UNIQUE (order_id, product_id),
                             CONSTRAINT ck_order_items_quantity CHECK (quantity > 0),
                             CONSTRAINT ck_order_items_unit_price CHECK (unit_price > 0),
                             CONSTRAINT ck_order_items_subtotal CHECK (subtotal = quantity * unit_price)
);

CREATE INDEX idx_order_items_order_id ON order_items (order_id);
CREATE INDEX idx_order_items_product_id ON order_items (product_id);

ALTER TABLE stock_movements
    ADD CONSTRAINT fk_stock_movements_orders
        FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE RESTRICT;