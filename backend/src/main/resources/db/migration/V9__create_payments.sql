CREATE TABLE payments (
                          id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
                          invoice_id   BIGINT        NOT NULL,
                          amount       NUMERIC(14,3) NOT NULL,
                          method       VARCHAR(20)   NOT NULL,
                          payment_date TIMESTAMPTZ   NOT NULL DEFAULT now(),
                          created_by   BIGINT        NOT NULL,
                          created_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
                          CONSTRAINT pk_payments PRIMARY KEY (id),
                          CONSTRAINT fk_payments_invoices FOREIGN KEY (invoice_id) REFERENCES invoices (id) ON DELETE RESTRICT,
                          CONSTRAINT fk_payments_users FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE RESTRICT,
                          CONSTRAINT ck_payments_amount CHECK (amount > 0),
                          CONSTRAINT ck_payments_method CHECK (method IN ('CASH', 'BANK_TRANSFER', 'CARD', 'CHECK'))
);

CREATE INDEX idx_payments_invoice_id ON payments (invoice_id);
CREATE INDEX idx_payments_payment_date ON payments (payment_date);