CREATE TABLE stock_movements (
                                 id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
                                 product_id      BIGINT       NOT NULL,
                                 quantity_change INTEGER      NOT NULL,
                                 quantity_after  INTEGER      NOT NULL,
                                 reason          VARCHAR(30)  NOT NULL,
                                 order_id        BIGINT,
                                 note            VARCHAR(255),
                                 created_by      BIGINT       NOT NULL,
                                 created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
                                 CONSTRAINT pk_stock_movements PRIMARY KEY (id),
                                 CONSTRAINT fk_stock_movements_products FOREIGN KEY (product_id) REFERENCES products (id) ON DELETE RESTRICT,
                                 CONSTRAINT fk_stock_movements_users FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE RESTRICT,
                                 CONSTRAINT ck_stock_movements_change CHECK (quantity_change <> 0),
                                 CONSTRAINT ck_stock_movements_after CHECK (quantity_after >= 0),
                                 CONSTRAINT ck_stock_movements_reason CHECK (reason IN
                                                                             ('INITIAL_STOCK', 'ORDER_CONFIRMED', 'ORDER_CANCELLED', 'MANUAL_ADJUSTMENT'))
);

CREATE INDEX idx_stock_movements_product_created ON stock_movements (product_id, created_at);

-- Historique rétroactif : un mouvement INITIAL_STOCK pour chaque produit déjà en stock.
INSERT INTO stock_movements (product_id, quantity_change, quantity_after, reason, note, created_by)
SELECT p.id, p.quantity, p.quantity, 'INITIAL_STOCK', 'Stock existant avant la mise en place de l''historique',
       (SELECT MIN(u.id) FROM users u)
FROM products p
WHERE p.quantity > 0;