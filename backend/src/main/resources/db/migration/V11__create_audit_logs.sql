-- Audit trail: who did what, on which record, when. Rows are only ever inserted.
-- No foreign key on purpose: the trail must outlive a deleted user and also keep the
-- failed logins of an e-mail address that does not exist.
CREATE TABLE audit_logs (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_email   VARCHAR(255) NOT NULL,
    action       VARCHAR(50)  NOT NULL,
    entity_type  VARCHAR(30),
    entity_id    BIGINT,
    entity_label VARCHAR(255),
    http_method  VARCHAR(10),
    path         VARCHAR(255),
    details      VARCHAR(500),
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_audit_logs PRIMARY KEY (id)
);

CREATE INDEX idx_audit_logs_created_at ON audit_logs (created_at DESC);
CREATE INDEX idx_audit_logs_user_email ON audit_logs (user_email);
CREATE INDEX idx_audit_logs_action ON audit_logs (action);
CREATE INDEX idx_audit_logs_entity ON audit_logs (entity_type, entity_id);
