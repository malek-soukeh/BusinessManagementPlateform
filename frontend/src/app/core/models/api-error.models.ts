/** Stable code of an API error (field `code`): the frontend reacts to it, never to the English message. */
export type ApiErrorCode =
  // Generic
  | 'VALIDATION_FAILED' | 'MALFORMED_REQUEST' | 'INVALID_PARAMETER' | 'UNAUTHENTICATED' | 'INVALID_CREDENTIALS'
  | 'ACCESS_DENIED' | 'RESOURCE_NOT_FOUND' | 'CONFLICT' | 'CONCURRENT_MODIFICATION' | 'DATA_INTEGRITY_VIOLATION'
  // Customers, users, products, stock
  | 'EMAIL_ALREADY_USED' | 'TAX_NUMBER_ALREADY_USED' | 'REFERENCE_ALREADY_USED' | 'CUSTOMER_INACTIVE'
  | 'PRODUCT_INACTIVE' | 'INSUFFICIENT_STOCK'
  // Categories
  | 'CATEGORY_NAME_ALREADY_USED' | 'CATEGORY_HAS_SUBCATEGORIES' | 'CATEGORY_USED_BY_PRODUCTS' | 'CATEGORY_IN_USE'
  | 'PARENT_CATEGORY_NOT_FOUND' | 'CATEGORY_CYCLE'
  // Orders
  | 'DUPLICATE_ORDER_PRODUCT' | 'ORDER_NOT_MODIFIABLE' | 'INVALID_ORDER_TRANSITION' | 'ORDER_HAS_ACTIVE_INVOICE'
  // Invoices and payments
  | 'ORDER_NOT_INVOICEABLE' | 'ORDER_ALREADY_INVOICED' | 'DISCOUNT_EXCEEDS_TOTAL' | 'DUE_DATE_BEFORE_ISSUE_DATE'
  | 'INVOICE_NOT_CANCELLABLE' | 'INVOICE_HAS_PAYMENTS' | 'INVOICE_NOT_PAYABLE' | 'PAYMENT_EXCEEDS_REMAINING'
  // Users
  | 'CANNOT_CHANGE_OWN_EMAIL' | 'CANNOT_CHANGE_OWN_ROLE' | 'CANNOT_DEACTIVATE_OWN_ACCOUNT'
  | 'CANNOT_DELETE_OWN_ACCOUNT' | 'USER_HAS_RECORDS';

/** JSON body of every error sent by the API. */
export interface ApiError {
  timestamp: string;
  status: number;
  error: string;
  code: ApiErrorCode;
  message: string;
  path: string;
}
